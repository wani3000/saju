test('linked member/recovery/other-owner/expired sessions cannot substitute for a fresh Kakao session',async()=>{
 const a=await s.newSession(db),b=await s.newSession(db),subject=randomUUID();
 await bindIdentity(db,a.owner,await startIdentity(db,a.owner),subject,{displayName:'김춘배',avatarUrl:'https://k.kakaocdn.net/a'});
 assert.equal(await hasKakaoSession(db,a.owner,s.hash(a.secret)),false);
 const recovery=await s.recover(db,await s.recoveryCode(db,a.owner));
 await assert.rejects(requireKakaoSession(db,a.owner,s.hash(recovery.secret)),{code:'KAKAO_LOGIN_REQUIRED'});
 await assert.rejects(s.newSession(db,b.owner,subject),{code:'INVALID_IDENTITY'});
 const verified=await s.newSession(db,a.owner,subject);
 assert.equal(await hasKakaoSession(db,a.owner,s.hash(verified.secret)),true);
 assert.equal(await hasKakaoSession(db,b.owner,s.hash(verified.secret)),false);
 await db.query("UPDATE sessions SET expires_at=now()-interval '1 second' WHERE token_hash=$1",[s.hash(verified.secret)]);
 assert.equal(await hasKakaoSession(db,a.owner,s.hash(verified.secret)),false);
 const newSession=await s.newSession(db,a.owner,subject);
 await erasePersonalData(db,a.owner);
 assert.equal(await hasKakaoSession(db,a.owner,s.hash(newSession.secret)),false);
 const record=await one(db,'SELECT display_name,avatar_url FROM auth_identities WHERE subject=$1',[subject]);
 assert.equal(record?.display_name,null);assert.equal(record?.avatar_url,null);
});
test('reading/payment histories are owner scoped, retain refunds, and never include payment credentials',async()=>{
 const a=await s.newSession(db),b=await s.newSession(db),pair={me:samplePerson(),other:samplePerson(true)};
 await bindIdentity(db,a.owner,await startIdentity(db,a.owner),randomUUID());
 const first=await s.createComparison(db,a.owner,pair,randomUUID(),true);await s.runJobs(db,a.owner);
 pair.other={...pair.other,id:randomUUID()};
 const second=await s.createComparison(db,a.owner,pair,randomUUID(),true);
 const order=(await one(db,'SELECT * FROM orders WHERE comparison_id=$1',[second.id]))!;
 await confirmPayment(db,a.owner,order.id,'mock_'+order.id,2900);await s.runJobs(db,a.owner);
 const before=await s.state(db,a.owner);
 assert.equal(before.readingHistory.length,2);assert.ok(before.readingHistory.every(r=>r.can_open));
 assert.equal(before.orders[0].other_name,pair.other.name);assert.ok(before.orders[0].created_at);
 assert.equal('payment_key' in before.orders[0],false);assert.equal('inputs' in before.readingHistory[0],false);
 await refundPayment(db,a.owner,order.id);
 const after=await s.state(db,a.owner),refunded=after.readingHistory.find(r=>r.id===second.id)!;
 assert.equal(refunded.can_open,false);assert.equal(after.orders[0].state,'refunded');
 assert.ok(after.results.some(r=>r.id===first.id));await assert.rejects(s.result(db,a.owner,second.id));
 const other=await s.state(db,b.owner);assert.equal(other.readingHistory.length,0);assert.equal(other.orders.length,0);
});
